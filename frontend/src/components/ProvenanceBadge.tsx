import type { Provenance } from "../api/types";

/** Shows whether content came from Gemini or from deterministic mock mode. Mock is never shown as AI output. */
export function ProvenanceBadge({ provenance }: { provenance: Provenance }) {
  const when = new Date(provenance.generatedAt).toLocaleString();
  if (provenance.isMock) {
    return (
      <span className="pill pill-mock" title={`Deterministic mock output (no LLM call) · ${when}`}>
        MOCK · not AI-generated
      </span>
    );
  }
  return (
    <span className="pill pill-ai" title={`Generated ${when}`}>
      Generated by Gemini · {provenance.model}
    </span>
  );
}
