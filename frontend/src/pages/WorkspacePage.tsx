import { useState } from "react";
import { Link, useNavigate, useParams, useSearchParams } from "react-router-dom";
import { api } from "../api/client";
import { AgentPipeline } from "../components/AgentPipeline";
import { BranchModal } from "../components/BranchModal";
import { MediaPanel } from "../components/MediaPanel";
import { VersionHistory } from "../components/VersionHistory";
import { CharactersPanel } from "../components/content/CharactersPanel";
import { PlanPanel } from "../components/content/PlanPanel";
import { ScreenplayPanel } from "../components/content/ScreenplayPanel";
import { StoryPanel } from "../components/content/StoryPanel";
import { StatusBadge } from "../components/StatusBadge";
import { useProjectAssets } from "../hooks/useAssets";
import { useProductionWorkspace } from "../hooks/useProductionWorkspace";

const TABS = [
  { key: "plan", label: "Production plan" },
  { key: "story", label: "Story" },
  { key: "characters", label: "Characters" },
  { key: "screenplay", label: "Screenplay & scenes" },
  { key: "assets", label: "Asset versions" },
  { key: "media", label: "Video & trailers" },
] as const;
type TabKey = (typeof TABS)[number]["key"];

export function WorkspacePage() {
  const { id = "" } = useParams();
  const navigate = useNavigate();
  const { project, content, error, starting, startGeneration } = useProductionWorkspace(id);
  const { assets } = useProjectAssets(id);
  const [searchParams] = useSearchParams();
  const [tab, setTab] = useState<TabKey>(() => {
    const requested = searchParams.get("tab");
    return TABS.some((t) => t.key === requested) ? (requested as TabKey) : "plan";
  });
  const [showBranchModal, setShowBranchModal] = useState(false);
  const [branching, setBranching] = useState(false);
  const [selectedVersionAsset, setSelectedVersionAsset] = useState<typeof assets[0] | null>(null);

  async function handleBranch(branchName: string) {
    setBranching(true);
    try {
      const branched = await api.branchProject(id, branchName);
      navigate(`/projects/${branched.id}`);
    } catch (e) {
      alert(e instanceof Error ? e.message : "Branch failed");
    } finally {
      setBranching(false);
      setShowBranchModal(false);
    }
  }

  if (!project) {
    return error ? (
      <p className="alert alert-danger">
        {error} <Link to="/">Back to projects</Link>
      </p>
    ) : (
      <p className="muted">Loading production…</p>
    );
  }

  const generating = project.status === "generating";
  const hasContent = Boolean(content.plan || content.story || content.characters || content.screenplay);

  return (
    <div className="workspace">
      <Link to="/" className="back-link">
        ← All productions
      </Link>

      <section className="card">
        <div className="card-header">
          <div>
            <h1>{project.title}</h1>
            <p className="muted">
              {project.genre} · {project.durationMinutes} minutes · <StatusBadge status={project.status} />
            </p>
          </div>
          <div className="header-actions">
            <button className="btn btn-primary" onClick={startGeneration} disabled={generating || starting}>
              {generating ? "Generating…" : project.status === "draft" ? "Start AI generation" : "Regenerate"}
            </button>
            <button className="btn btn-secondary" onClick={() => setShowBranchModal(true)} disabled={generating}>
              Branch
            </button>
          </div>
        </div>
        <p className="idea">{project.idea}</p>
        {error && <p className="alert alert-danger">{error}</p>}
        {project.lastError && project.status === "failed" && (
          <p className="alert alert-danger">Generation failed: {project.lastError}</p>
        )}
      </section>

      {project.agentRuns.length > 0 && (
        <section className="card">
          <h2>Agent status</h2>
          <AgentPipeline runs={project.agentRuns} />
        </section>
      )}

      {project.llm?.isMock && project.agentRuns.length > 0 && (
        <p className="alert alert-mock">
          <strong>Mock mode.</strong> This production was generated by the deterministic development mock because no
          Gemini API key is configured. The content below is placeholder output, not AI-generated.
        </p>
      )}

      {hasContent && (
        <section className="card">
          <nav className="tabs">
            {TABS.map((t) => (
              <button key={t.key} className={`tab ${tab === t.key ? "tab-active" : ""}`} onClick={() => setTab(t.key)}>
                {t.label}
              </button>
            ))}
          </nav>
          <div className="tab-body">
            {tab === "plan" && <PlanPanel plan={content.plan} />}
            {tab === "story" && <StoryPanel story={content.story} />}
            {tab === "characters" && <CharactersPanel characters={content.characters} />}
            {tab === "screenplay" && <ScreenplayPanel screenplay={content.screenplay} />}
            {tab === "media" &&
              (content.screenplay && content.screenplay.scenes.length > 0 && !generating ? (
                <MediaPanel projectId={id} scenes={content.screenplay.scenes} />
              ) : (
                <p className="muted">Videos are rendered from the screenplay's scenes. Finish AI generation first.</p>
              ))}
            {tab === "assets" && (
              <div className="assets-panel">
                <p className="muted small">
                  Every generation creates a new version. Versions are never overwritten.
                  {assets.length > 0 && ` ${assets.length} asset version${assets.length !== 1 ? "s" : ""} recorded.`}
                </p>
                {assets.length === 0 && <p className="muted">No asset versions yet. Generate content to create assets.</p>}
                <div className="project-asset-list">
                  {["plan", "story", "character", "screenplay", "scene"].map((type) => {
                    const typeAssets = assets.filter((a) => a.type === type);
                    if (typeAssets.length === 0) return null;
                    // Show unique assetIds (grouped by logical asset)
                    const byAssetId = new Map<string, typeof typeAssets[0]>();
                    typeAssets.forEach((a) => { if (!byAssetId.has(a.assetId) || a.version > byAssetId.get(a.assetId)!.version) byAssetId.set(a.assetId, a); });
                    return (
                      <div key={type} className="project-asset-group">
                        <h4 className="asset-group-label">{type.charAt(0).toUpperCase() + type.slice(1)}s</h4>
                        {Array.from(byAssetId.values()).map((asset) => (
                          <div key={asset.assetId} className="project-asset-row">
                            <span>
                              {asset.type === "character" ? String(asset.content["name"] ?? asset.assetId.slice(0, 8)) : `v${asset.version}`}
                            </span>
                            <span className="muted small">{asset.version} version{asset.version !== 1 ? "s" : ""}</span>
                            {asset.sourceAssetIds.length > 0 && (
                              <span className="pill pill-reused small">↺ reused context</span>
                            )}
                            <button
                              className="btn-link"
                              onClick={() => setSelectedVersionAsset(selectedVersionAsset?.assetId === asset.assetId ? null : asset)}
                            >
                              {selectedVersionAsset?.assetId === asset.assetId ? "hide" : "history"}
                            </button>
                            <button className="btn-link accent" onClick={() => navigate(`/assets?type=${type}`)}>
                              library ↗
                            </button>
                          </div>
                        ))}
                        {selectedVersionAsset && selectedVersionAsset.type === type && (
                          <VersionHistory asset={selectedVersionAsset} />
                        )}
                      </div>
                    );
                  })}
                </div>
              </div>
            )}
          </div>
        </section>
      )}
      {showBranchModal && (
        <BranchModal
          projectTitle={project.title}
          onConfirm={handleBranch}
          onCancel={() => setShowBranchModal(false)}
          loading={branching}
        />
      )}
    </div>
  );
}
